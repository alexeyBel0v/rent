export const calcPrice = (days: number) => {
  if (days >= PRICES.monthDays) return days * PRICES.monthPerDay;
  if (days <= PRICES.minDays) return PRICES.minPrice;
  return PRICES.minPrice + (days - PRICES.minDays) * PRICES.perDay;
};

